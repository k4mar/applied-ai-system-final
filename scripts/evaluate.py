"""Run the coach reliability evaluation and write a markdown + JSON report.

Usage:
    python scripts/evaluate.py                    # offline provider (reproducible)
    python scripts/evaluate.py --provider openai  # same experiments on the live LLM
    python scripts/evaluate.py --quick            # Normal only, for a fast check

Outputs:
    docs/evaluation_report.md     human-readable tables
    docs/evaluation_results.json  the same numbers, machine-readable
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from dataclasses import asdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def row(*cells) -> str:
    """Format one markdown table row."""
    return "| " + " | ".join(str(c) for c in cells) + " |"


def yes(flag: bool) -> str:
    return "yes" if flag else "no"


def main(argv=None) -> int:
    # Imported here (after the path tweak) so the script runs from any folder
    # without installing the project as a package.
    sys.path.insert(0, str(ROOT))
    from coach.agent import CoachAgent
    from coach.evaluation import (
        evaluate_retrieval,
        run_autoplay,
        run_consistency,
        run_fault_injection,
    )
    from coach.llm import get_provider
    from coach.logging_setup import configure_logging
    from coach.retriever import Retriever

    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--provider", choices=["auto", "openai", "offline"], default="offline"
    )
    ap.add_argument("--quick", action="store_true", help="Normal difficulty only")
    ap.add_argument("--out", default=str(ROOT / "docs"))
    args = ap.parse_args(argv)

    configure_logging()
    retriever = Retriever.from_directory()
    agent = CoachAgent(provider=get_provider(args.provider), retriever=retriever)
    started = time.perf_counter()

    autoplay = run_autoplay(agent, ["Normal"] if args.quick else None)
    faults = run_fault_injection(retriever, repair=True)
    faults_no_repair = run_fault_injection(retriever, repair=False)
    consistency = run_consistency(agent)
    retrieval = evaluate_retrieval(retriever)
    elapsed = round(time.perf_counter() - started, 2)

    games = sum(a.games for a in autoplay)
    wins = sum(a.wins for a in autoplay)
    caught = sum(f.first_try_caught for f in faults)
    should_catch = sum(1 for f in faults if f.name != "markdown_fenced_json")
    safe = sum(f.final_safe for f in faults + faults_no_repair)
    consistent = sum(r["consistent"] for r in consistency)
    hit1 = sum(r["hit_at_1"] for r in retrieval)
    hit3 = sum(r["hit_at_3"] for r in retrieval)
    n_ret, n_faults = len(retrieval), 2 * len(faults)

    summary = {
        "provider": agent.provider.name,
        "seconds": elapsed,
        "autoplay_win_rate": f"{wins}/{games}",
        "faults_caught": f"{caught}/{should_catch}",
        "faults_final_advice_safe": f"{safe}/{n_faults}",
        "consistency": f"{consistent}/{len(consistency)}",
        "retrieval_hit_at_1": f"{hit1}/{n_ret}",
        "retrieval_hit_at_3": f"{hit3}/{n_ret}",
    }

    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    results = {
        "summary": summary,
        "autoplay": [asdict(a) for a in autoplay],
        "fault_injection_with_repair": [asdict(f) for f in faults],
        "fault_injection_no_repair": [asdict(f) for f in faults_no_repair],
        "consistency": consistency,
        "retrieval": retrieval,
    }
    (out / "evaluation_results.json").write_text(
        json.dumps(results, indent=2), encoding="utf-8"
    )

    md = [
        "# Coach evaluation report",
        "",
        f"Generated by `python scripts/evaluate.py --provider {args.provider}`",
        f"(provider used: `{agent.provider.name}`, {elapsed}s).",
        "",
        "## Summary",
        "",
        row("Metric", "Result"),
        row("---", "---"),
        row("Autoplay: games won following the coach every turn", f"{wins}/{games}"),
        row(
            "Fault injection: bad outputs caught on first check",
            summary["faults_caught"],
        ),
        row(
            "Fault injection: final advice still safe (with and without repair)",
            summary["faults_final_advice_safe"],
        ),
        row(
            "Consistency: identical advice across 5 repeats",
            f"{consistent}/{len(consistency)} positions",
        ),
        row("Retrieval: expected passage ranked #1", f"{hit1}/{n_ret}"),
        row("Retrieval: expected passage in top 3", f"{hit3}/{n_ret}"),
        "",
        "## 1. Autoplay (every secret, every difficulty)",
        "",
        row(
            "Difficulty",
            "Games",
            "Wins",
            "Mean attempts",
            "Worst case",
            "Attempt limit",
            "Answer modes",
            "Mean / min confidence",
        ),
        row(*["---"] * 8),
    ]
    for a in autoplay:
        md.append(
            row(
                a.difficulty,
                a.games,
                a.wins,
                a.mean_attempts,
                a.max_attempts,
                a.attempt_limit,
                a.modes,
                f"{a.mean_confidence} / {a.min_confidence}",
            )
        )
    md += [
        "",
        "## 2. Fault injection",
        "",
        "Position: Normal, guesses `60 (Too High)`, `20 (Too Low)`,",
        "so the live interval is 21-59. Each fault is injected as the model's first",
        "answer. *With repair*, the second answer is well-formed; *without repair*,",
        "the fault repeats every time.",
        "",
        row(
            "Fault",
            "Simulates",
            "Caught",
            "Final mode (repair)",
            "Final mode (no repair)",
            "Final guess",
            "Safe",
        ),
        row(*["---"] * 7),
    ]
    for f, g in zip(faults, faults_no_repair, strict=True):
        md.append(
            row(
                f"`{f.name}`",
                f.simulates,
                yes(f.first_try_caught),
                f.final_mode,
                g.final_mode,
                f.final_guess,
                yes(f.final_safe and g.final_safe),
            )
        )
    md += [
        "",
        "`markdown_fenced_json` is a control case: the answer is correct but wrapped",
        "in a code fence, which real models often do. It should be *accepted*, not",
        "rejected, so it is excluded from the caught count.",
        "",
        "## 3. Consistency",
        "",
        row("Position", "Suggestions over 5 runs", "Consistent"),
        row("---", "---", "---"),
    ]
    for r in consistency:
        md.append(row(r["position"], r["suggestions"], yes(r["consistent"])))
    md += [
        "",
        "## 4. Retrieval",
        "",
        row("Situation", "Expected passage", "Hit@1", "Hit@3"),
        row("---", "---", "---", "---"),
    ]
    for r in retrieval:
        md.append(
            row(
                ", ".join(r["situation"]),
                f"`{r['expected']}`",
                yes(r["hit_at_1"]),
                yes(r["hit_at_3"]),
            )
        )
    (out / "evaluation_report.md").write_text("\n".join(md) + "\n", encoding="utf-8")

    for k, v in summary.items():
        print(f"{k:28} {v}")
    print(f"report: {out / 'evaluation_report.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
